// What the generated workflows of the e2e scenarios share: they start from the repository's WORKFLOW.md, live in the run
// directory and so need paths that no longer depend on the workflow's directory.
import path from 'node:path';
import YAML from 'yaml';
import { isPlainObject } from '../../src/workflow/loader.ts';

/** Status timeline of a run (`timeline.jsonl` in the run directory), one JSON object per line. */
export const TIMELINE_FILE = 'timeline.jsonl';

type Config = Record<string, unknown>;

/** Makes a path from the source workflow independent of the workflow's directory. */
export function absolute(value: unknown, root: string): unknown {
  if (typeof value !== 'string' || value === '' || value.startsWith('$') || value.startsWith('~') || path.isAbsolute(value)) return value;
  return path.resolve(root, value);
}

/** The front matter section `key` as a mutable copy that replaces the original in `config` (created when missing). */
export function section(config: Config, key: string): Config {
  const value = config[key];
  const copy = isPlainObject(value) ? { ...value } : {};
  config[key] = copy;
  return copy;
}

/**
 * Makes the settings that point into the repository work from the run directory: the workspace root, the paths in the
 * hooks (`$SYMPHONY_WORKFLOW_DIR`), the plugins and the Claude executable. Laravel Boost is switched off, the test
 * issues change no code.
 */
export function independentOfWorkflowDir(config: Config, root: string): void {
  const workspace = section(config, 'workspace');
  workspace.root = absolute(workspace.root, root);

  // Hooks may call scripts next to WORKFLOW.md.
  const hooks = section(config, 'hooks');
  for (const [key, value] of Object.entries(hooks)) {
    if (typeof value === 'string') hooks[key] = value.replace(/\$\{?SYMPHONY_WORKFLOW_DIR\}?/g, root);
  }

  const claude = section(config, 'claude');
  if (Array.isArray(claude.plugins)) claude.plugins = claude.plugins.map((plugin) => absolute(plugin, root));
  if (typeof claude.executable === 'string' && claude.executable.includes('/')) claude.executable = absolute(claude.executable, root);

  if (isPlainObject(config.laravel)) config.laravel = { ...config.laravel, boost: 'off' };
}

/** The workflow file: a header naming the generator, the front matter and the prompt. */
export function renderWorkflow(config: Config, prompt: string, generator: string, root: string): string {
  return `---\n# Generated by ${generator} from ${path.join(root, 'WORKFLOW.md')}; do not edit.\n${YAML.stringify(config)}---\n${prompt}`;
}
